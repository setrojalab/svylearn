test_that("decision totals, net benefit and percentiles obey hand calculations", {
  y<-c(0,1,0,1);p<-c(.1,.8,.6,.4);w<-c(1,2,3,4)
  z<-svy_decision(y,p,w,.5)
  expect_equal(unname(unlist(z[c("tp","fp","tn","fn")])),c(2,3,1,4))
  expect_equal(z$net_benefit,-.1)
  expect_equal(z$treat_all,.2)
  expect_equal(z$sensitivity,1/3)
  expect_equal(svy_percentile(c(.1,.1,.9),c(1,3,6)),c(.2,.2,.7))
  bins<-svy_calibration_bins(y,p,w,bins=2)
  expect_equal(sum(bins$weight),sum(w))
  expect_equal(sum(bins$weight*bins$observed)/sum(w),sum(w*y)/sum(w))
  expect_error(svy_decision(y,p,w,0),"strictly")
  expect_error(svy_calibration_bins(y,p,w,bins=1),"integer")
  expect_error(svy_curves(y,p,w,max_fpr=2),"max_fpr")
  expect_error(svy_align_prevalence(p,w,1),"prevalence")
})

test_that("SHAP aggregates and subgroup suppression match the declared target", {
  skip_if_not_installed("survey")
  d<-svy_example(400);z<-svy_design(d,"weight","psu","stratum")
  sh<-cbind(x1=d$x1,x2=d$x2);out<-svy_shap(z,sh)
  expect_equal(out$mean_absolute_shap,colSums(abs(sh)*d$weight)/sum(d$weight),ignore_attr=TRUE)
  sub<-svy_subgroups(z,d$y,plogis(d$x1),ifelse(d$x2>0,"a","b"),min_events=1)
  expect_true(all(vapply(sub,function(x)!is.null(x$inference),logical(1))))
  sub<-svy_subgroups(z,d$y,plogis(d$x1),d$stratum,min_events=100)
  expect_true(all(vapply(sub,function(x)is.null(x$inference),logical(1))))
  expect_error(svy_shap(z,matrix(NA_real_,400,2)),"Invalid")
  expect_error(svy_subgroups(z,d$y,plogis(d$x1),c(1,2)),"Invalid")
})

test_that("spline calibration is usable and constant predictions are explicit", {
  d<-svy_example(400);p<-plogis(-2+d$x1)
  cal<-svy_calibrate(d$y,p,d$weight,method="spline")
  expect_true(all(is.finite(predict(cal,p))))
  expect_true(is.finite(svy_calibration_error(d$y,p,d$weight)$ICI))
  constant<-svy_calibrate(d$y,rep(.3,400),d$weight)
  expect_match(constant$status,"constant")
  expect_length(unique(predict(constant,p)),1)
})

test_that("custom learners receive training weights and predict at the declared length", {
  d<-svy_example(200);z<-svy_design(d,"weight","psu","stratum")
  spec<-svy_learner("custom",fit=function(x,y,w)sum(w*y)/sum(w),
                    predict=function(model,x)rep(model,nrow(x)))
  f<-svy_fit(z,"y",c("x1","x2"),learners=list(spec),v=3,inner_v=2,calibration="none",stack=TRUE)
  expect_equal(unique(predict(f,d)),weighted.mean(d$y,d$weight))
  expect_output(print(f),"Survey-aware")
  file<-tempfile(fileext=".pdf");grDevices::pdf(file);plot(f);grDevices::dev.off()
  expect_true(file.info(file)$size>0)
  expect_error(svy_learner("custom"),"Provide")
})

test_that("recipe extrapolation and invalid inputs have defined behavior", {
  d<-data.frame(x=1:100,z=rep(1,100),f=rep(c("a","b"),50));w<-seq_len(100)
  rec<-svy_recipe(d,w,winsor=c(.1,.9),spline_df=3)
  m<-bake_svy_recipe(rec,data.frame(x=c(-100,NA,1000),z=c(1,1,1),f=c("a","new",NA)))
  expect_true(all(is.finite(m)))
  expect_equal(nrow(m),3)
  rec2<-svy_recipe(d,w,scale=FALSE)
  expect_equal(bake_svy_recipe(rec2,d)[,"x"],as.numeric(d$x))
  expect_error(svy_recipe(d,w,winsor=c(.9,.1)),"Invalid")
  expect_error(svy_recipe(d,w,spline_df=-1),"Invalid")
  expect_error(bake_svy_recipe(rec,data.frame(x=1)),"Required")
  expect_error(bake_svy_recipe(rec,transform(d,x=as.character(x))),"changed type")
  expect_error(svy_recipe(data.frame(f=rep(NA_character_,4))),"no observed")
  rec3<-svy_recipe(data.frame(f=rep("a",4)))
  expect_error(bake_svy_recipe(rec3,data.frame(f="a")),"No nonconstant")
})

test_that("invalid design and inference specifications fail before estimation", {
  d<-svy_example(200);z<-svy_design(d,"weight","psu","stratum")
  expect_error(svy_design(d,"absent"),"Unknown")
  expect_error(svy_design(d[FALSE,],"weight"),"nonempty")
  dn<-d;dn$weight[1]<-NA
  expect_error(svy_design(dn,"weight"),"missing")
  expect_error(svy_design(d,"weight",repweights=matrix(1,200,2)),"explicit")
  expect_error(svy_design(d,"weight",repweights=matrix(-1,200,2)),"Invalid")
  expect_error(svy_split(z,v=1),"at least")
  expect_error(svy_split(z,v=100),"Fewer")
  expect_error(svy_fit(z,"y","x1",learners=list()),"nonempty")
  expect_error(svy_fit(z,"y","x1",inner_v=1),"inner_v")
  expect_error(svy_diagnostics(z,y=c(0,1)),"mismatch")
  expect_error(svy_infer(z,d$y,plogis(d$x1),domain=rep(FALSE,200)),"Invalid domain")
  expect_error(svy_infer(z,d$y,plogis(d$x1),level=2),"confidence")
  expect_error(svy_infer(z,d$y[1:10],rep(.1,10)),"Row count")
  expect_error(svy_export(1,tempfile()),"data frame")
  independent<-svy_design(d,"weight")
  expect_s3_class(as_survey_design(independent),"survey.design")
  panel<-svy_example(100,waves=2)
  independent_panel<-svy_design(panel,"weight",subject="subject",wave="wave")
  expect_s3_class(as_survey_design(independent_panel),"survey.design")
})
