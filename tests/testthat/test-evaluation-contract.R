  expect_error(svy_transport(source, target, source_prediction = 1:3), "Both")
  expect_error(svy_transport(source, target[,1,drop=FALSE]), "matching")
})

test_that("conformal thresholds retain test-point mass and boundary ties", {
  a <- svy_conformal(1:9, rep(0,9), c(0,10), alpha = .1)
  expect_equal(a$threshold, c(9,9))
  expect_equal(a$sets, cbind(lower = c(-9,1), upper = c(9,19)))
  b <- svy_conformal(1:8, rep(0,8), 0, alpha = .1)
  expect_true(is.infinite(b$threshold))
  c <- svy_conformal(1:9, rep(0,9), 0, w = rep(2,9), test_weights = 2, alpha = .2,
    weight_type = "covariate_shift")
  expect_equal(c$threshold, 8)
  cc <- svy_conformal(1:9, rep(0,9), 0, w = rep(20,9), test_weights = 20, alpha = .2,
    weight_type = "covariate_shift")
  expect_equal(cc$threshold, c$threshold)
  d <- svy_conformal(1:9, rep(0,9), 0, w = rep(1,9), test_weights = 99,
    weight_type = "survey")
  expect_true(is.infinite(d$threshold)); expect_match(d$assumption, "not guaranteed")
  expect_error(svy_conformal(1:9, rep(0,9), 0, w=1:9), "identical")
  expect_error(svy_conformal(1:9, rep(0,9), 0, weight_type="survey"), "test_weights")
  y <- factor(c("a","b","a","b"), levels=c("a","b")); pp <- cbind(a=c(.8,.2,.7,.3),b=c(.2,.8,.3,.7))
  m <- svy_conformal(y, pp, pp, alpha=.4, family="multinomial")
  expect_true(all(m$sets[cbind(1:4,as.integer(y))]))
  bb <- svy_conformal(c(0,1,0,1), c(.1,.8,.2,.9), c(.1,.9), alpha=.4, family="binomial")
  expect_equal(bb$sets, cbind(`0`=c(TRUE,FALSE),`1`=c(FALSE,TRUE)))
})

