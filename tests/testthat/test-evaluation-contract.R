  expect_error(svy_eval(z, d$y, rep(.1, 240), transport = list()), "Invalid transport")
})

test_that("population utility matches direct survey totals and ratios", {
  skip_if_not_installed("survey")
  d <- data.frame(y = c(0,1,0,1,0,1,1,0), p = c(.1,.8,.6,.4,.3,.7,.9,.2),
    w = c(1,2,3,4,2,1,3,2), id = 1:8)
  z <- svy_design(d, "w", "id"); ds <- as_survey_design(z)
  a <- svy_decision_infer(z, d$y, d$p, .5)
  get <- function(k) a$estimate[a$metric == k]
  tp <- as.numeric(d$y==1 & d$p>=.5); fp <- as.numeric(d$y==0 & d$p>=.5)
  expect_equal(get("pop_tp"), sum(d$w*tp)); expect_equal(get("pop_fp"), sum(d$w*fp))
  expect_equal(get("nns_svy"), sum(d$w*(tp+fp))/sum(d$w*tp))
  expect_equal(get("nns_population"), sum(d$w)/sum(d$w*tp))
  expect_equal(get("net_benefit_svy"), sum(d$w*(tp-fp))/sum(d$w))
  expect_equal(get("net_benefit_per_100000"), get("net_benefit_svy")*1e5)
  direct <- survey::svyratio(~I(as.numeric(p>=.5)), ~I(as.numeric(y==1 & p>=.5)), ds)
  expect_equal(a$se[a$metric=="nns_svy"], sqrt(unname(vcov(direct)[1,1])))
  b <- svy_decision_infer(z, d$y, d$p, .5, population_size = 1000)
  expect_equal(b$estimate[b$metric=="pop_tp"], sum(d$w*tp)/sum(d$w)*1000)
  c <- svy_decision_infer(z, d$y, d$p, .99)
  expect_true(all(is.infinite(c$estimate[c$metric %in% c("nns_svy","nns_population")])))
  expect_error(svy_decision_infer(z, d$y, d$p, 1), "strictly")
})

test_that("event residual is distinct from demographic raking", {
  skip_if_not_installed("survey")
  d <- svy_example(400); z <- svy_design(d, "weight", "psu", "stratum")
  pop <- c(`(Intercept)` = sum(d$weight), x1 = 0)
  rd <- svy_rake(z, ~x1, pop)
  a <- svy_rake_audit(z, rep(.2,400), .1*sum(d$weight), rd, ~x1, pop)
  expect_equal(a$rake_residual, 1, tolerance = 1e-8)
  expect_equal(a$margins$absolute_residual, c(0,0), tolerance = 1e-8)
  expect_true(is.na(a$margins$relative_residual[2]))
  b <- svy_rake_audit(z, rep(.1,400), .1*sum(d$weight), rd)
  expect_equal(b$rake_residual, 0, tolerance = 1e-8)
  expect_error(svy_rake_audit(z, rep(.1,400), 0), "positive")
})

test_that("transport uses frozen reference SD and separates divergence from outcome loss", {
  source <- cbind(x = c(0,1,2), constant = 1)
  target <- cbind(constant = 1, x = c(1,2,3))
  a <- svy_transport(source, target, transport_weights = c(0,1,2),
    source_prediction = c(.1,.2,.3), target_prediction = c(.2,.4,.6), target_outcome = c(0,0,1))
  expect_equal(a$transport_smd$before, c(-1/sqrt(2/3),0))
  expect_equal(a$transport_smd$after[1], (5/3-2)/sqrt(2/3))
