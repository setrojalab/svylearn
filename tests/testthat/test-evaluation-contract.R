test_that("domain contrasts retain covariance and max-gap envelopes contain estimates", {
  skip_if_not_installed("survey")
  set.seed(7); d <- svy_example(1600); d$y <- rbinom(1600,1,plogis(.2+.3*d$x1))
  z <- svy_design(d,"weight","psu","stratum"); p <- plogis(d$x1); g <- ifelse(d$x2>0,"A","B")
  a <- svy_domain_calibration(z,d$y,p,g)
  expect_equal(a$domain_cal_gap[1], max(abs(a$coefficients$estimate[c(1,3)])),ignore_attr=TRUE)
  expect_equal(a$domain_cal_gap[2], max(abs(a$coefficients$estimate[c(2,4)]-1)),ignore_attr=TRUE)
  expect_equal(a$contrasts$se[1],sqrt(a$covariance[1,1]+a$covariance[3,3]-2*a$covariance[1,3]))
  expect_true(all(a$intervals$ci_lower<=a$intervals$estimate & a$intervals$estimate<=a$intervals$ci_upper))
  empty <- svy_domain_calibration(z,d$y,p,g,min_events=1000)
  expect_match(empty$status,"No domain")
  one <- svy_domain_calibration(z,d$y,p,rep("all",1600))
  expect_null(one$contrasts); expect_equal(nrow(one$coefficients),2L)
})

test_that("replicate evaluation refits calibration smoother and rejects misaligned designs", {
  skip_if_not_installed("survey")
  d <- svy_example(800); z <- svy_design(d,"weight","psu","stratum"); p <- plogis(-2+d$x1)
  rd <- svy_replicates(z,type="JKn")
  a <- svy_eval(z,d$y,p,replicate_design=rd)
  direct <- survey::withReplicates(rd,function(w,data) {
    k <- w>0; c <- svy_calibration_error(d$y[k],p[k],w[k]); c(ici_svy=c$ICI,e90_svy=c$E90)
  })
  i <- match(c("ici_svy","e90_svy"),a$intervals$metric)
  expect_equal(a$intervals$se[i],sqrt(diag(vcov(direct))),ignore_attr=TRUE)
  wrong <- rd; wrong$variables$psu <- rev(wrong$variables$psu)
  expect_error(svy_eval(z,d$y,p,replicate_design=wrong),"identifiers")
  sh <- svy_shap(z,cbind(a=d$x1,b=d$x2),replicate_design=rd)
  expect_true(all(sh$ci_lower<=sh$shap_svy & sh$shap_svy<=sh$ci_upper))
})

test_that("permutation inference preserves panel trajectories and agrees with weighted differences", {
  skip_if_not_installed("survey")
  d <- svy_example(100,waves=3); z <- svy_design(d,"weight","psu","stratum",subject="subject",wave="wave")
  groups <- svylearn:::.permutation_rows(z)
  moved <- svylearn:::.permute_feature(d$subject,groups)
  expect_true(all(vapply(split(moved,d$subject),function(v)length(unique(v))==1L,logical(1))))
  expect_true(all(vapply(split(moved,z$cluster),function(v)length(unique(v))>0,logical(1))))
  f <- svy_fit(z,"y",c("x1","x2"),v=3,inner_v=2)
  a <- svy_importance_infer(f,repeats=2)
  expected <- tapply(a$draws$loss_increase,a$draws$feature,mean)
  expect_equal(a$vip_psu$vip_psu,as.numeric(expected[a$vip_psu$feature]))
  expect_match(a$permutation_unit,"whole subjects")
  expect_true(a$permutable_row_fraction>0)
  expect_error(svy_importance_infer(f,repeats=0),"positive")
  eval <- svy_eval(f,importance=a)
  expect_equal(eval$vip_psu,a$vip_psu)
})
