test_that("loss audit uses the frozen unweighted SRS variance reference", {
  skip_if_not_installed("survey")
  d <- svy_example(800); z <- svy_design(d, "weight", "psu", "stratum")
  p <- plogis(-2 + d$x1); ell <- -(d$y * log(p) + (1-d$y) * log1p(-p))
  a <- svy_eval(z, d$y, p, iid_predictions = p)
  mu <- weighted.mean(ell, d$weight); linear <- d$weight * (ell-mu) / sum(d$weight)
  bypsu <- tapply(linear, list(d$stratum, d$psu), sum)
  variance <- sum(apply(bypsu, 1, function(v) length(v)/(length(v)-1) * sum((v-mean(v))^2)))
  expect_equal(a$loss_svy, mu, tolerance = 1e-12)
  expect_equal(a$deff_loss, variance/(var(ell)/nrow(d)), tolerance = 1e-11)
  expect_equal(a$n_eff_pred, nrow(d)/a$deff_loss)
  expect_equal(a$optimism_bias, mean(ell)-mu)
  expect_equal(nrow(svy_glossary()), 17L)
  expect_equal(sort(na.omit(svy_glossary()$core)), as.numeric(1:12))
  expect_true(all(c("rake_residual", "transport_smd", "conf_coverage", "sensitivity_gamma",
    "net_benefit_svy", "domain_cal_gap", "shap_svy", "vip_psu") %in% names(a)))
  expect_true(is.na(a$rake_residual))
  expect_output(print(a, interpret = TRUE), "observed contrast")
  expect_s3_class(summary(a), "svy_eval")
  constant <- svy_eval(z, d$y, rep(.5, nrow(d)))
  expect_true(is.na(constant$deff_loss))
  expect_true(is.na(constant$n_eff_pred))
  expect_error(svy_eval(z, d$y, p, active_predictors = -1), "nonnegative")
})

