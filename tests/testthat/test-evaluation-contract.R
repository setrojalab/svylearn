test_that("bounded-weight optimization agrees with exhaustive box vertices", {
  values <- c(-1,0,2,3); w <- c(1,2,1,4); gamma <- 2
  corners <- as.matrix(expand.grid(rep(list(c(1/gamma,gamma)),4)))
  actual <- apply(corners,1,function(u)weighted.mean(values,w*u))
  a <- svy_weight_bounds(values,w,c(1,2))
  expect_equal(a$lower[2],min(actual)); expect_equal(a$upper[2],max(actual))
  expect_equal(a$lower[1],weighted.mean(values,w))
  expect_equal(a$upper[1],weighted.mean(values,w))
  expect_equal(svy_weight_bounds(values,w*10,2)$lower,a$lower[2])
  d <- data.frame(w=c(1,4), id=1:2); z <- svy_design(d,"w","id")
  tipping <- svy_sensitivity(z,c(-1,1),gamma=c(1,1.5,2,3))
  expect_equal(tipping$sensitivity_gamma,2,tolerance=1e-7)
  expect_true(tipping$global_point_optimum)
  expect_equal(svy_sensitivity(z,c(1,2))$sensitivity_gamma,Inf)
  expect_equal(svy_sensitivity(z,c(-2,-1))$sensitivity_gamma,1)
  expect_error(svy_weight_bounds(values,w,.5),"at least")
})

